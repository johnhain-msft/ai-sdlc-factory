// The committed render of examples/ is the golden set of the engine (design H.4). Every test that reads a generated workflow reads it through the preset seam, so
// what is committed must be what the renderer produces today: an engine change that alters the output regenerates examples/ in the same commit
// (node tools/update-examples.mjs --compile), and the diff of examples/ is then the behaviour change of that commit. This file reads examples/ itself.
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { renderFleet } from "../src/reconcile.mjs";
import { engineAbs } from "./helpers/preset.mjs";

const EXAMPLES = engineAbs("examples");
const W = ".github/workflows";
const REGENERATE = "node tools/update-examples.mjs --compile";
const request = JSON.parse(fs.readFileSync(path.join(EXAMPLES, "request.reference.json"), "utf8"));
const rendered = renderFleet(request, { cwd: EXAMPLES });
const committed = (name) => fs.readFileSync(path.join(EXAMPLES, name), "utf8");
const committedWorkflows = () => fs.readdirSync(path.join(EXAMPLES, W)).sort();
const sha256 = (text) => crypto.createHash("sha256").update(text).digest("hex");

const RENDERED = [
  "aw.json",
  "cascade-ai-course-to-hub.md",
  "cascade-ai-lab-to-hub.md",
  "cascade-ai-pipelines-to-hub.md",
  "cascade-mechanical-config-to-registry.md",
  "cascade-mechanical-docs-to-hub.md",
  "cascade-mechanical-orchestrator-to-hub.md",
  "cascade-router.yml",
  "drift-agent-kit.md",
  "drift-docs-site.md",
  "drift-lab-content.md",
  "implement-agent-kit.md",
  "implement-docs-site.md",
  "implement-lab-content.md",
  "sdlc-onboard.md",
];
const SOURCES = RENDERED.filter((name) => name.endsWith(".md"));

test("the reference request renders the example fleet: fifteen files, the thirteen workflow sources, the router and aw.json", () => {
  assert.equal(rendered.ok, true, JSON.stringify(rendered.result));
  assert.deepEqual([...rendered.files.keys()].sort(), RENDERED.map((name) => `${W}/${name}`));
  assert.equal(SOURCES.length, 13);
});

test("every rendered file is byte for byte the committed one", () => {
  for (const [name, text] of rendered.files) assert.equal(committed(name), text, `${name} is not what the renderer produces: regenerate with ${REGENERATE}`);
});

test("the committed workflows directory holds the rendered files and the thirteen locks, and nothing else", () => {
  assert.deepEqual(committedWorkflows(), [...RENDERED, ...SOURCES.map((name) => name.replace(/\.md$/, ".lock.yml"))].sort());
});

test("every source has a lock that the pinned gh-aw compiled in strict mode, and the lock is fresh for the prompt: its body hash is the SHA-256 of the source's body", () => {
  const pinned = committed(".gh-aw-version").trim();
  for (const name of SOURCES) {
    const lock = committed(`${W}/${name.replace(/\.md$/, ".lock.yml")}`);
    const [header, ...rest] = lock.split("\n");
    assert.match(header, /^# gh-aw-metadata: \{.*\}$/, `${name}: the first line of the lock is its metadata`);
    const metadata = JSON.parse(header.replace("# gh-aw-metadata: ", ""));
    assert.equal(metadata.compiler_version, pinned, `${name}: compiled by ${metadata.compiler_version}, not by the pinned ${pinned}`);
    assert.equal(metadata.strict, true, `${name}: compiled in strict mode`);
    assert.match(metadata.frontmatter_hash, /^[0-9a-f]{64}$/, name);
    assert.ok(rest.some((line) => line.includes(`automatically generated by gh-aw (${pinned})`)), `${name}: generated by the pinned gh-aw`);
    const source = committed(`${W}/${name}`);
    const body = /^---\n[\s\S]*?\n---\n?([\s\S]*)$/.exec(source)?.[1];
    assert.notEqual(body, undefined, `${name} has a frontmatter`);
    assert.equal(metadata.body_hash, sha256(body.trim()), `${name}: the lock was compiled from another prompt than the committed source: regenerate with ${REGENERATE}`);
  }
});

test("the pin cache of the compiler is committed: every entry names a repository, a version and a full commit", () => {
  const { entries } = JSON.parse(committed(".github/aw/actions-lock.json"));
  assert.ok(Object.keys(entries).length >= 1);
  for (const [uses, pin] of Object.entries(entries)) {
    assert.equal(uses, `${pin.repo}@${pin.version}`);
    assert.match(pin.sha, /^[0-9a-f]{40}$/, uses);
  }
});

test("the committed files are UTF-8 without a byte order mark, with LF line endings and one final newline", () => {
  for (const name of committedWorkflows()) {
    const bytes = fs.readFileSync(path.join(EXAMPLES, W, name));
    assert.notDeepEqual([...bytes.subarray(0, 3)], [0xef, 0xbb, 0xbf], `${name}: a byte order mark`);
    assert.equal(bytes.includes(0x0d), false, `${name}: a carriage return`);
    assert.equal(bytes.at(-1), 0x0a, `${name}: no final newline`);
    assert.notEqual(bytes.at(-2), 0x0a, `${name}: more than one final newline`);
  }
});
